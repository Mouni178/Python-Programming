# What is Classification?
# Classification is a type of Supervised Machine Learning algorithm
# used to predict categorical (class) values.

# Definition:
# Classification learns from labeled data and predicts
# which category or class a new data point belongs to.

# Examples of Classification
# - Email Spam Detection (Spam / Not Spam)
# - Disease Prediction (Positive / Negative)
# - Face Recognition
# - Handwritten Digit Recognition
# - Loan Approval (Approved / Rejected)

# Types of Classification
# 1. Binary Classification
# Predicts one of two possible classes.
# Examples:
# - Yes / No
# - True / False
# - Spam / Not Spam
# - Pass / Fail

# 2. Multiclass Classification
# Predicts one class from more than two classes.
# Examples:
# - Classifying animals (Dog, Cat, Horse)
# - Recognizing handwritten digits (0–9)
# - Predicting traffic sign categories

# Basic Terminology

# Independent Variable (X)
# Input features used to make predictions.
# Examples:
# - Age
# - Income
# - Marks
# - Height

# Dependent Variable (Y)
# Output class that we want to predict.
# Examples:
# - Pass / Fail
# - Spam / Not Spam
# - Approved / Rejected

# Example
# Hours Studied (X)     Result (Y)
# 2                     Fail
# 4                     Pass
# 6                     Pass
# 1                     Fail

# The model learns the relationship between
# Hours Studied and Result and predicts whether
# a new student will Pass or Fail.

# Advantages of Classification
# - Easy to classify data into categories.
# - Used in many real-world applications.
# - High accuracy with good-quality data.

# Disadvantages of Classification
# - Requires labeled data.
# - Performance depends on data quality.
# - Can make incorrect predictions if the model is not trained well.

