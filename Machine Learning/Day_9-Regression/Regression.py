# What is Regression?
# Regression is a type of Supervised Machine Learning algorithm
# used to predict continuous (numerical) values.

# Definition:
# Regression finds the relationship between the input (independent variable)
# and the output (dependent variable) to predict future values.

# Examples of Regression
# - House Price Prediction
# - Salary Prediction
# - Temperature Prediction
# - Stock Price Prediction
# - Sales Prediction

# Types of Regression

# 1. Linear Regression
# Used when the relationship between input and output is linear
# (represented by a straight line).

# Example:
# Predict house price based on house area.

# 2. Multiple Linear Regression
# Uses two or more independent variables to predict one dependent variable.

# Example:
# Predict house price using:
# - Area
# - Number of Bedrooms
# - Location

# Basic Terminology

# Independent Variable (X)
# Input feature used to make predictions.
# Example:
# House Area

# Dependent Variable (Y)
# Output that we want to predict.
# Example:
# House Price

# Simple Example

# X (Area in sq.ft.)     Y (Price in Lakhs)
# 1000                   30
# 1200                   35
# 1500                   45
# 1800                   55

# The model learns the relationship between Area and Price
# and predicts the price of a new house.

# Advantages of Regression
# - Simple to understand
# - Easy to implement
# - Predicts continuous values
# - Widely used in forecasting

# Disadvantages of Regression
# - Assumes a linear relationship (for Linear Regression)
# - Sensitive to outliers
# - Performance decreases with poor-quality data

# Real-Life Applications
# - House Price Prediction
# - Sales Forecasting
# - Weather Forecasting
# - Stock Market Analysis
# - Demand Prediction
# - Electricity Consumption Prediction

